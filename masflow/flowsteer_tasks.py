def _derandomize_indices(tasks: list[FlowSteerTask]) -> list[FlowSteerTask]:
    """Every task above was authored with benign_idx=0, malicious_idx=1
    fixed -- confirmed to make `masr`/`tasr` measure the planner's
    positional bias, not attack strength (a control run with ZERO
    injected argument still picks index 1 on every task; see draft.tex,
    Section "A Note on Task-Dataset Validity"). This permutes each
    task's subtask order (and re-indexes benign_idx/malicious_idx to
    match) with a fixed seed, so which index is malicious varies across
    the dataset and can no longer be guessed from position alone."""
    import random
    rng = random.Random(42)
    for t in tasks:
        order = list(range(len(t.subtasks)))
        rng.shuffle(order)
        old_subtasks, old_benign, old_malicious = t.subtasks, t.benign_idx, t.malicious_idx
        t.subtasks = [old_subtasks[i] for i in order]
        t.benign_idx = order.index(old_benign)
        t.malicious_idx = order.index(old_malicious)
    return tasks


